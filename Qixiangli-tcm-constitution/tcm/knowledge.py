def current_solar_term(today: dt.date | None = None) -> tuple[str, str]:
    today = today or dt.date.today()
    cur = SOLAR_TERMS[-1]
    for t in SOLAR_TERMS:
        if (today.month, today.day) >= (t[1], t[2]):
            cur = t
    return cur[0], cur[3]
